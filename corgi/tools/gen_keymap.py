#!/usr/bin/env python3
"""Generate src/keymap.h from Ghostty's src/input/keycodes.zig.

Each row maps a W3C code ("KeyA", "Enter") and Ghostty's key name ("a",
"enter") to the native keycodes Ghostty expects in
ghostty_input_key_s.keycode: the macOS virtual keycode, and on Linux the
XKB keycode (evdev + 8).

    python3 tools/gen_keymap.py ghostty/src/input/keycodes.zig > src/keymap.h
"""
import re
import sys

src = open(sys.argv[1]).read()

names = dict(re.findall(r'\.\{\s*"(\w+)",\s*\.(\w+)\s*\}', src))
rows = re.findall(
    r'\.\{\s*0x[0-9a-f]+,\s*0x[0-9a-f]+,\s*(0x[0-9a-f]+),\s*0x[0-9a-f]+,\s*(0x[0-9a-f]+),\s*"(\w*)"\s*\}',
    src,
)

print("// Generated by tools/gen_keymap.py from Ghostty's src/input/keycodes.zig.")
print("// W3C code, Ghostty key name, macOS virtual keycode (0xffff: none),")
print("// XKB keycode (0: none).")
print("static const struct { const char *code; const char *name; unsigned mac, xkb; } KEYMAP[] = {")
for xkb, mac, code in rows:
    if (mac == "0xffff" and xkb == "0x0000") or code not in names:
        continue
    name = names[code]
    if name.startswith("key_"):
        name = name[4:]
    print(f'  {{"{code}", "{name}", {mac}, {xkb}}},')
print("};")
